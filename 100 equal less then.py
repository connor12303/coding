number = input('enter a number')
number = float(number)
if number == 100:
    print('number is equal to')
if number > 100:
    print('number is greater then')
if number < 100:
    print('number is less then')
if number >= 100:
    print('number is greater then or equal to')
if number <= 100:
    print('number is less then or equal to')
if number != 100:
    print('number is not equal to')